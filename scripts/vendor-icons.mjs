import fs from 'node:fs'
import path from 'node:path'
import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const rootDir = path.resolve(__dirname, '..')
const frontendSrc = path.join(rootDir, 'frontend/src')
const outDir = path.join(frontendSrc, 'shared/components/icons')

const require = createRequire(import.meta.url)
const lucidePkgPath = require.resolve('lucide-react/package.json', {
  paths: [path.join(rootDir, 'frontend')],
})
const lucideEsmDir = path.join(path.dirname(lucidePkgPath), 'dist/esm')
const lucideEntry = fs.readFileSync(path.join(lucideEsmDir, 'lucide-react.js'), 'utf8')

// Build map: ExportedName -> icon file path (from lucide-react.js re-exports)
const exportToFile = new Map()
for (const line of lucideEntry.split('\n')) {
  const m = line.match(/^export\s+\{\s*default\s+as\s+(\w+)(?:\s*,\s*default\s+as\s+\w+)*\s*\}\s+from\s+'([^']+)'/)
  if (m) {
    const fileRel = m[2]
    const allAliases = [...line.matchAll(/default\s+as\s+(\w+)/g)].map((x) => x[1])
    for (const alias of allAliases) {
      exportToFile.set(alias, path.resolve(lucideEsmDir, fileRel))
    }
  }
}

function walk(dir, files = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) walk(full, files)
    else if (/\.(ts|tsx)$/.test(entry.name)) files.push(full)
  }
  return files
}

const usedNames = new Set()
const importRe = /import\s+(type\s+)?\{([^}]+)\}\s+from\s+['"]lucide-react['"]/g
for (const file of walk(frontendSrc)) {
  const src = fs.readFileSync(file, 'utf8')
  let match
  while ((match = importRe.exec(src)) !== null) {
    if (match[1]) continue
    for (const part of match[2].split(',')) {
      const trimmed = part.trim()
      if (!trimmed || trimmed.startsWith('type ')) continue
      const name = trimmed.split(/\s+as\s+/)[0].trim()
      if (name) usedNames.add(name)
    }
  }
}

const sortedNames = [...usedNames].sort()
const iconNodes = new Map()

for (const name of sortedNames) {
  const iconFile = exportToFile.get(name)
  if (!iconFile || !fs.existsSync(iconFile)) {
    throw new Error(`Could not resolve lucide-react icon "${name}"`)
  }
  const src = fs.readFileSync(iconFile, 'utf8')
  const nodeMatch = src.match(/createLucideIcon\("[^"]+",\s*(\[[\s\S]*?\])\s*\);/)
  if (!nodeMatch) {
    throw new Error(`Could not parse iconNode from ${iconFile}`)
  }
  // Evaluate the static array literal safely via JSON-like parse
  const nodeData = new Function(`return (${nodeMatch[1]})`)()
  iconNodes.set(name, nodeData)
}

fs.mkdirSync(outDir, { recursive: true })

const createIconSource = `import { createElement, forwardRef, type ForwardRefExoticComponent, type RefAttributes, type SVGProps } from 'react'

export type IconNode = Array<[tag: string, attrs: Record<string, string>]>

export interface LucideProps extends SVGProps<SVGSVGElement> {
  size?: string | number
  absoluteStrokeWidth?: boolean
}

export type LucideIcon = ForwardRefExoticComponent<Omit<LucideProps, 'ref'> & RefAttributes<SVGSVGElement>>

export function createLucideIcon(iconName: string, iconNode: IconNode): LucideIcon {
  const Component = forwardRef<SVGSVGElement, LucideProps>(
    ({ color = 'currentColor', size = 24, strokeWidth = 2, absoluteStrokeWidth, className, children, ...rest }, ref) =>
      createElement(
        'svg',
        {
          ref,
          xmlns: 'http://www.w3.org/2000/svg',
          width: size,
          height: size,
          viewBox: '0 0 24 24',
          fill: 'none',
          stroke: color,
          strokeWidth: absoluteStrokeWidth ? (Number(strokeWidth) * 24) / Number(size) : strokeWidth,
          strokeLinecap: 'round',
          strokeLinejoin: 'round',
          className: className ? \`lucide \${className}\` : 'lucide',
          ...rest,
        },
        ...iconNode.map(([tag, attrs]) => createElement(tag, attrs)),
        children,
      ),
  )
  Component.displayName = iconName
  return Component
}
`

fs.writeFileSync(path.join(outDir, 'create-icon.tsx'), createIconSource, 'utf8')

const lines = [
  '// Generated by scripts/vendor-icons.mjs from lucide-react (ISC License). Do not edit manually.',
  "import { createLucideIcon, type IconNode } from './create-icon'",
  "export type { LucideIcon, LucideProps } from './create-icon'",
  '',
]

for (const name of sortedNames) {
  const data = JSON.stringify(iconNodes.get(name))
  lines.push(`export const ${name} = createLucideIcon('${name}', ${data} as IconNode)`)
}
lines.push('')

fs.writeFileSync(path.join(outDir, 'index.ts'), lines.join('\n'), 'utf8')
console.log(`Generated ${sortedNames.length} icons in ${path.relative(rootDir, outDir)}`)
